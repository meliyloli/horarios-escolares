// Incapacidades: registrar una ausencia, decidir «sin reemplazo, que lleguen tarde» y leer el resumen para enviar.
const espera = (ms) => new Promise((r) => setTimeout(r, ms))
const comprobar = (ok, t) => console.log(`${ok ? 'OK   ' : 'FALLA'} ${t}`)
export default async ({ pagina, clic, foto }) => {
  await clic('Colegio', 'nav button')
  await clic('Llenar con un horario típico')
  await espera(200)
  await pagina.evaluate(() => document.querySelector('#titulo-horas')?.scrollIntoView())
  await foto('129-horas-franjas', false)
  await clic('Horario', 'nav button')
  await clic('Generar horario')
  await pagina.waitForFunction(() => /Cruces pendientes/.test(document.body.textContent), { timeout: 30000 })
  await espera(4500)
  await clic('Incapacidades', 'nav button')
  await pagina.evaluate(() => {
    const f = document.querySelector('input[type=date]')
    Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value').set.call(f, '2026-11-16')
    f.dispatchEvent(new Event('input', { bubbles: true }))
    const s = [...document.querySelectorAll('label.campo')].find((l) => l.textContent.startsWith('Docente ausente')).querySelector('select')
    Object.getOwnPropertyDescriptor(HTMLSelectElement.prototype, 'value').set.call(s, [...s.options].find((o) => o.textContent === 'Beatriz Elena Zapata').value)
    s.dispatchEvent(new Event('change', { bubbles: true }))
  })
  await espera(200)
  await clic('Registrar ausencia')
  await espera(300)
  await foto('130-ausencia-pregunta', false)
  await pagina.evaluate(() => [...document.querySelectorAll('label.opcion')].find((l) => l.textContent.startsWith('Sin reemplazo')).querySelector('input').click())
  await espera(300)
  await pagina.evaluate(() => [...document.querySelectorAll('label.marca')].find((l) => l.textContent === 'Que lleguen tarde').querySelector('input').click())
  await espera(400)
  const textos = await pagina.$$eval('textarea.mensaje', (xs) => xs.map((x) => x.value))
  console.log(textos.join('\n-----\n'))
  comprobar(/ingresa a las \d+:\d\d [ap]\. m\./.test(textos[1] ?? ''), 'el mensaje para familias dice a qué hora entran')
  comprobar(!/sin docente/i.test(textos[0] ?? ''), 'el mensaje a docentes no lista horas sin docente')
  comprobar(/, en [^.]+\./.test(textos[0] ?? ''), 'el mensaje a docentes trae el aula')
  await pagina.evaluate(() => document.querySelector('fieldset.decision')?.scrollIntoView())
  await foto('131-ausencia-resumen', false)
}
