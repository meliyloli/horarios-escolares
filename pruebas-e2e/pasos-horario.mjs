const espera = (ms) => new Promise((r) => setTimeout(r, ms))

export default async ({ pagina, clic, foto }) => {
  await clic('Horario', 'nav button')
  await foto('10-horario-vacio')
  await clic('Generar horario')
  await pagina.waitForFunction(() => document.body.textContent.includes('Cruces pendientes'), { timeout: 30000 })
  await espera(300)
  await foto('11-horario-grupo')
  // Mover una clase: seleccionar la primera y soltarla sobre otra celda del grupo.
  const clases = await pagina.$$('.horario .clase')
  await clases[0].click()
  await espera(200)
  await foto('12-seleccion', false)
  const otra = await pagina.$$('.horario .clase')
  await otra[7].click()
  await espera(300)
  await foto('13-con-cruces')
  await clic('Por docente', '[role=tab]')
  await foto('14-docente')
  await clic('General', '[role=tab]')
  await foto('15-general', false)
  await clic('Por grupo', '[role=tab]')
  await pagina.evaluate(() => { window.print = () => {} })
  await pagina.emulateMediaType('print')
  await pagina.select('select[aria-label="Qué imprimir o exportar"]', 'todos')
  await clic('Imprimir', 'header button')
  await espera(400)
  const hojas = await pagina.evaluate(() => [...document.querySelectorAll('.hoja')].filter((h) => h.getBoundingClientRect().height > 100).length)
  console.log(hojas === 16 ? 'impresión: 16 hojas visibles' : `ERROR: se ven ${hojas} hojas al imprimir, se esperaban 16`)
  await pagina.pdf({ path: `${process.argv[2]}/16-impresion.pdf`, landscape: true, printBackground: true, preferCSSPageSize: true })
  await pagina.emulateMediaType('screen')
}
