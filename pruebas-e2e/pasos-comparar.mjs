// Las mismas cuatro vistas para comparar el diseño antes y después. Carpeta en CARPETA_FOTOS.
const espera = (ms) => new Promise((r) => setTimeout(r, ms))
export default async ({ pagina, clic, foto }) => {
  await clic('Horario', 'nav button')
  await clic('Generar horario')
  await pagina.waitForFunction(() => /Cruces pendientes|No se pudo ubicar/.test(document.body.textContent), { timeout: 30000 })
  await espera(4500)
  await foto('1-horario', false)
  await clic('Asignación académica', 'nav button')
  await clic('Por grupo', '[role=tab]')
  await foto('2-asignacion', false)
  await clic('Colegio', 'nav button')
  await foto('3-colegio', false)
  await clic('Incapacidades', 'nav button')
  await pagina.evaluate(() => {
    const f = document.querySelector('input[type=date]')
    Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value').set.call(f, '2026-11-16')
    f.dispatchEvent(new Event('input', { bubbles: true }))
    const s = [...document.querySelectorAll('label.campo')].find((l) => l.textContent.startsWith('Docente ausente')).querySelector('select')
    Object.getOwnPropertyDescriptor(HTMLSelectElement.prototype, 'value').set.call(s, s.options[3].value)
    s.dispatchEvent(new Event('change', { bubbles: true }))
  })
  await espera(200)
  await clic('Registrar ausencia')
  await espera(300)
  await pagina.evaluate(() => [...document.querySelectorAll('label.opcion')].find((l) => l.textContent.startsWith('Con el reemplazo'))?.querySelector('input').click())
  await espera(400)
  await foto('4-incapacidades', false)
}
