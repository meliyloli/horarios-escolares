// Recorre cada pantalla con el horario generado y toma la primera vista (lo que se ve sin desplazar).
const espera = (ms) => new Promise((r) => setTimeout(r, ms))
export default async ({ pagina, clic, foto }) => {
  await clic('Colegio', 'nav button')
  await foto('c01-colegio', false)
  await clic('Áreas e intensidad', 'nav button')
  await foto('c02-areas', false)
  await clic('Grupos, docentes y aulas', 'nav button')
  await foto('c03-grupos', false)
  await clic('Asignación académica', 'nav button')
  await foto('c04-asignacion', false)
  await clic('Horario', 'nav button')
  await foto('c05-horario-vacio', false)
  await clic('Generar horario')
  await pagina.waitForFunction(() => /Cruces pendientes|No se pudo ubicar/.test(document.body.textContent), { timeout: 30000 })
  await espera(4500)
  await foto('c06-horario', false)
  await clic('Por docente', '[role=tab]')
  await foto('c07-horario-docente', false)
  await clic('Acompañamiento', 'nav button')
  await foto('c08-acompanamiento', false)
  await clic('Incapacidades', 'nav button')
  await foto('c09-incapacidades', false)
  await clic('Colegios y versiones', 'nav button')
  await foto('c10-versiones', false)
}
